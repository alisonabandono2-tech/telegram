// Requer Playwright. Execute contra browser_server.py, nunca contra uma conta real.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||undefined,headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const failures=[];page.on('pageerror',e=>failures.push(e.message));
 await page.goto('http://localhost:3000');
 await page.getByLabel('Telefone',{exact:true}).fill('+5511000000000');
 await page.getByRole('button',{name:'Receber código',exact:true}).click();
 await page.getByLabel('Código',{exact:true}).fill('12345');
 await page.getByRole('button',{name:'Confirmar código',exact:true}).click();
 await page.getByLabel('Senha 2FA',{exact:true}).fill('fictional-password');
 await page.getByRole('button',{name:'Entrar',exact:true}).click();
 await page.getByText('● Conta conectada',{exact:true}).waitFor();
 await page.locator('.importbar input').setInputFiles({name:'leads.csv',mimeType:'text/csv',buffer:Buffer.from('Nome,username,ID\nAna,alice_test,11\nBia,bia_test,22\nSem usuario,,33\n')});
 await page.getByText('2 contatos · 0 enviados',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Ana @alice_test · Pendente',exact:true}).click();
 await page.getByLabel('Mensagem',{exact:true}).fill('Olá {nome}, esta é uma mensagem fictícia de teste.');
 await page.getByRole('checkbox',{name:'Usar formatação (negrito/itálico)',exact:true}).check();
 await page.getByLabel('Mensagem',{exact:true}).evaluate(field=>{field.focus();field.setSelectionRange(0,10)});
 await page.getByRole('button',{name:'Negrito',exact:true}).click();
 await page.locator('.message-preview b').filter({hasText:'Olá Ana'}).waitFor();
 assert.ok((await page.getByLabel('Mensagem',{exact:true}).inputValue()).includes('<b>Olá {nome}</b>'));

 await page.locator('.preview-text').filter({hasText:'Olá Ana, esta é uma mensagem fictícia de teste.'}).waitFor();
 const send=page.getByRole('button',{name:'Enviar para este contato',exact:true});
 assert.equal(await send.isEnabled(),false);
 await page.locator('.attachment input').setInputFiles({name:'imagem.png',mimeType:'image/png',buffer:Buffer.from(process.env.TEST_IMAGE_BASE64,'base64')});
 await page.getByAltText('Imagem selecionada',{exact:true}).waitFor();
 await page.locator('.confirm-send input').check();
 await send.click();
 await page.getByText('Mensagem enviada para @alice_test.',{exact:true}).waitFor();
 await page.getByText('2 contatos · 1 enviados',{exact:true}).waitFor();
 const response=await page.request.get('http://localhost:3000/api/backend/leads');
 const leads=await response.json();
 assert.equal(leads.filter(x=>x.status==='sent').length,1);
 assert.equal(leads.find(x=>x.username==='bia_test').status,'pending');
 const blocked=await page.request.post('http://localhost:3000/api/backend/auth/phone',{data:{phone:'fictional'}});
 assert.equal(blocked.status(),403,'POST sem Origin deve ser rejeitado');
 await page.screenshot({path:process.env.SCREENSHOT_PATH||'/tmp/telegram-contacts-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Próximo contato →',exact:true}).click();
 await page.getByRole('heading',{name:'Bia',exact:true}).waitFor();
 assert.equal(await page.locator('.confirm-send input').isChecked(),false);
 await page.getByRole('button',{name:'Bloquear contato',exact:true}).click();
 await page.locator('.status-chip').filter({hasText:'Bloqueado'}).waitFor();

 page.once('dialog',dialog=>dialog.dismiss());
 await page.getByRole('button',{name:'Excluir contato',exact:true}).click();
 assert.equal((await (await page.request.get('http://localhost:3000/api/backend/leads')).json()).length,2);
 page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'Excluir contato',exact:true}).click();
 await page.getByText('Contato @bia_test excluído da lista.',{exact:true}).waitFor();
 await page.getByText('1 contatos · 1 enviados',{exact:true}).waitFor();
 await page.locator('.importbar input').setInputFiles({name:'leads.csv',mimeType:'text/csv',buffer:Buffer.from('Nome,username,ID\nAna,alice_test,11\nBia,bia_test,22\n')});
 await page.getByText(/1 excluídos anteriormente/).waitFor();
 assert.equal((await (await page.request.get('http://localhost:3000/api/backend/leads')).json()).length,1);
 await page.getByLabel('Pesquisar contatos',{exact:true}).fill('alice');
 assert.equal(await page.locator('.lead-item').count(),1);
 await page.setViewportSize({width:390,height:844});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 assert.equal(overflow,false,'Interface mobile não deve ter overflow horizontal');
 page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'Excluir contato',exact:true}).click();
 await page.getByText('0 contatos · 0 enviados',{exact:true}).waitFor();
 await page.getByRole('heading',{name:'Escolha um contato',exact:true}).waitFor();
 assert.deepEqual(failures,[]);
 console.log('Browser: login + 2FA, CSV, personalização, botão Negrito e prévia formatada, imagem, confirmação, um envio simulado, próximo, bloqueio, busca, origem, mobile, cancelar/confirmar exclusão, reimportação e lista vazia: OK');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
